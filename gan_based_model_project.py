# GAN - Generative Adversarial Network
# ==========================================
# Import Libraries
# ==========================================

import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf

from tensorflow.keras import layers
from tensorflow.keras.datasets import mnist


# ============================================
# Load MNIST Dataset
# ============================================

(X_train, _), (_, _) = mnist.load_data()

# Normalize images from 0-255 to -1 to 1
X_train = X_train.astype("float32")
X_train = (X_train - 127.5) / 127.5

# Add channel dimension
X_train = np.expand_dims(X_train, axis=-1)

print("Dataset shape:", X_train.shape)


# ============================================
# Create Dataset
# ============================================

BUFFER_SIZE = 60000
BATCH_SIZE = 128

dataset = tf.data.Dataset.from_tensor_slices(X_train)
dataset = dataset.shuffle(BUFFER_SIZE).batch(BATCH_SIZE)


# ============================================
# Create Generator
# ============================================

def build_generator():

    model = tf.keras.Sequential([

        layers.Dense(7 * 7 * 128, input_shape=(100,)),
        layers.BatchNormalization(),
        layers.LeakyReLU(),

        layers.Reshape((7, 7, 128)),

        layers.Conv2DTranspose(
            64,
            kernel_size=4,
            strides=2,
            padding="same"
        ),
        layers.BatchNormalization(),
        layers.LeakyReLU(),

        layers.Conv2DTranspose(
            1,
            kernel_size=4,
            strides=2,
            padding="same",
            activation="tanh"
        )
    ])

    return model


generator = build_generator()

generator.summary()


# ============================================
# Create Discriminator
# ============================================

def build_discriminator():

    model = tf.keras.Sequential([

        layers.Conv2D(
            64,
            kernel_size=4,
            strides=2,
            padding="same",
            input_shape=(28, 28, 1)
        ),
        layers.LeakyReLU(),
        layers.Dropout(0.3),

        layers.Conv2D(
            128,
            kernel_size=4,
            strides=2,
            padding="same"
        ),
        layers.LeakyReLU(),
        layers.Dropout(0.3),

        layers.Flatten(),

        layers.Dense(1)
    ])

    return model


discriminator = build_discriminator()

discriminator.summary()


# ============================================
# CELL 6: Loss Functions and Optimizers
# ============================================

cross_entropy = tf.keras.losses.BinaryCrossentropy(
    from_logits=True
)

generator_optimizer = tf.keras.optimizers.Adam(
    learning_rate=0.0002,
    beta_1=0.5
)

discriminator_optimizer = tf.keras.optimizers.Adam(
    learning_rate=0.0002,
    beta_1=0.5
)


# ============================================
# Define Training Step
# ============================================

noise_dim = 100


@tf.function
def train_step(images):

    noise = tf.random.normal(
        [BATCH_SIZE, noise_dim]
    )

    with tf.GradientTape() as gen_tape, \
         tf.GradientTape() as disc_tape:

        # Generate fake images
        fake_images = generator(
            noise,
            training=True
        )

        # Discriminator predictions
        real_output = discriminator(
            images,
            training=True
        )

        fake_output = discriminator(
            fake_images,
            training=True
        )

        # Generator loss
        gen_loss = cross_entropy(
            tf.ones_like(fake_output),
            fake_output
        )

        # Discriminator loss
        real_loss = cross_entropy(
            tf.ones_like(real_output),
            real_output
        )

        fake_loss = cross_entropy(
            tf.zeros_like(fake_output),
            fake_output
        )

        disc_loss = real_loss + fake_loss

    # Calculate gradients
    gradients_of_generator = gen_tape.gradient(
        gen_loss,
        generator.trainable_variables
    )

    gradients_of_discriminator = disc_tape.gradient(
        disc_loss,
        discriminator.trainable_variables
    )

    # Update models
    generator_optimizer.apply_gradients(
        zip(
            gradients_of_generator,
            generator.trainable_variables
        )
    )

    discriminator_optimizer.apply_gradients(
        zip(
            gradients_of_discriminator,
            discriminator.trainable_variables
        )
    )

    return gen_loss, disc_loss


# ============================================
# Generate Sample Images
# ============================================

seed = tf.random.normal(
    [16, noise_dim]
)


def generate_images(model, epoch):

    predictions = model(
        seed,
        training=False
    )

    predictions = (predictions + 1) / 2

    plt.figure(figsize=(8, 8))

    for i in range(16):

        plt.subplot(4, 4, i + 1)

        plt.imshow(
            predictions[i, :, :, 0],
            cmap="gray"
        )

        plt.axis("off")

    plt.suptitle(
        "Generated Images - Epoch " + str(epoch)
    )

    plt.show()


# ============================================
# Train GAN
# ============================================

EPOCHS = 20

for epoch in range(EPOCHS):

    for image_batch in dataset:

        gen_loss, disc_loss = train_step(
            image_batch
        )

    print(
        f"Epoch {epoch + 1}/{EPOCHS} "
        f"| Generator Loss: {gen_loss:.4f} "
        f"| Discriminator Loss: {disc_loss:.4f}"
    )

    generate_images(generator, epoch + 1)


# ============================================
# Generate Final Images
# ============================================

noise = tf.random.normal(
    [25, noise_dim]
)

generated_images = generator(
    noise,
    training=False
)

generated_images = (
    generated_images + 1
) / 2


plt.figure(figsize=(10, 10))

for i in range(25):

    plt.subplot(5, 5, i + 1)

    plt.imshow(
        generated_images[i, :, :, 0],
        cmap="gray"
    )

    plt.axis("off")

plt.suptitle("Final GAN Generated Digits")

plt.show()


# ============================================
# Save Generator
# ============================================

generator.save("simple_gan_generator.keras")

print("GAN model saved successfully!")